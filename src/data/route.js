/**
 * 예시 도착 정보 계산.
 * stopT : 정류장의 노선 위 위치(0~1), busTs : 버스들의 위치(0~1), stopTs : 모든 정류장 위치
 * 가장 먼저 도착하는 버스 순으로 돌려준다.
 * waiting = 버스가 이미 지나가 다음 운행(기점 출발)을 기다리는 상태
 */
export function arrivals(stopT, busTs, stopTs) {
  return busTs
    .map((t, bus) => {
      const waiting = t > stopT + 0.002;
      const dist = waiting ? 1 - t + stopT : Math.max(0, stopT - t);
      const before = waiting
        ? stopTs.filter((s) => s <= stopT + 1e-6).length
        : stopTs.filter((s) => s > t + 1e-6 && s <= stopT + 1e-6).length;
      return { bus, t, waiting, dist, before, minutes: Math.max(1, Math.ceil(dist * TRIP_MINUTES)) };
    })
    .sort((a, b) => a.dist - b.dist);
}

/** 도착 정보를 화면 문구로 */
export function describe(a) {
  if (a.waiting) return { eta: `약 ${a.minutes}분`, where: '기점 출발 전', soon: false };
  if (a.dist < 0.012) return { eta: '곧 도착', where: '정류장 진입 중', soon: true };
  return { eta: `약 ${a.minutes}분`, where: a.before <= 1 ? '전 정류장 출발' : `${a.before} 정류장 전`, soon: a.minutes <= 2 };
}
